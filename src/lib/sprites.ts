export type SpriteName = keyof typeof SPRITES

/** SVG markup for use outside React (the click-burst overlay). */
export function spriteSvg(name: SpriteName, size = 4, color = '#0a0a0a'): string {
  const rects = SPRITES[name]
    .flatMap((row, y) => [...row].map((c, x) => (c === '#' ? `<rect x="${x}" y="${y}" width="1" height="1"/>` : '')))
    .join('')
  return `<svg class="sprite" width="${8 * size}" height="${8 * size}" viewBox="0 0 8 8" fill="${color}" aria-hidden="true">${rects}</svg>`
}
